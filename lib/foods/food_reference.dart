import 'package:food_ration/nutrition/ingredient.dart';
import 'package:food_ration/nutrition/macros.dart';

/// Продукт с КБЖУ на 100 г — для расчёта своих блюд.
class FoodRef {
  const FoodRef(this.name, this.kcal, this.protein, this.fat, this.carbs, {this.pieceG, this.custom = false});

  final String name;
  final double kcal;
  final double protein;
  final double fat;
  final double carbs;

  /// Вес одной штуки, если продукт удобно считать штуками.
  final double? pieceG;

  /// Свой продукт пользователя (а не из справочника).
  final bool custom;

  Macros get per100 => Macros(kcal: kcal, protein: protein, fat: fat, carbs: carbs);

  Macros forGrams(double g) => per100 * (g / 100);

  List<String> get tokens => Ingredient.nameTokens(name);
}

/// Поиск по справочнику: все слова запроса должны встречаться в названии.
List<FoodRef> searchFoods(String query, Iterable<FoodRef> foods, {int limit = 50}) {
  final words = Ingredient.nameTokens(query);
  final q = query.trim().toLowerCase().replaceAll('ё', 'е');
  if (q.isEmpty) return foods.take(limit).toList();
  final scored = <(int, FoodRef)>[];
  for (final f in foods) {
    final name = f.name.toLowerCase().replaceAll('ё', 'е');
    int score;
    if (name.startsWith(q)) {
      score = 0;
    } else if (name.contains(q)) {
      score = 1;
    } else if (words.isNotEmpty && words.every((w) => f.tokens.any((t) => Ingredient.tokensMatch(w, t) || t.startsWith(w)))) {
      score = 2;
    } else {
      continue;
    }
    scored.add((f.custom ? score - 1 : score, f));
  }
  scored.sort((a, b) {
    final s = a.$1.compareTo(b.$1);
    return s != 0 ? s : a.$2.name.length.compareTo(b.$2.name.length);
  });
  return [for (final s in scored.take(limit)) s.$2];
}

